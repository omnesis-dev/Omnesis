/**
 * `npm run search-eval:report` — rebuild `evals/search/RESULTS.md` from the
 * committed runs.
 *
 * `npm run search-eval:report -- --compare <base> <candidate>` instead prints a
 * query-by-query comparison of two runs: the change per language with a 95%
 * paired bootstrap interval. Both runs must have scored the same queries.
 */

import { writeFileSync } from "node:fs";
import { join } from "node:path";
import * as prettier from "prettier";

import { LANGUAGE_NAMES, type Language } from "./dataset.js";
import { mean, pairedBootstrap, percentile, seededRandom } from "./metrics.js";
import {
  listRuns,
  readQueryRows,
  readSummary,
  RESULTS_DIR,
  type QueryRow,
  type RunSummary,
} from "./results.js";

type Metric = "hit10" | "ndcg10" | "recall100" | "mrr10";
const METRIC_LABELS: Readonly<Record<Metric, string>> = {
  hit10: "Hit@10",
  ndcg10: "nDCG@10",
  recall100: "Recall@100",
  mrr10: "MRR@10",
};
const BOOTSTRAP_ROUNDS = 2000;
const BOOTSTRAP_SEED = 20261114;

function fmt(value: number): string {
  return value.toFixed(3);
}

function signed(value: number): string {
  return `${value >= 0 ? "+" : "−"}${Math.abs(value).toFixed(3)}`;
}

function table(header: readonly string[], rows: readonly (readonly string[])[]): string {
  const line = (cells: readonly string[]): string => `| ${cells.join(" | ")} |`;
  const rule = header.map((_, i) => (i === 0 ? "---" : "---:"));
  return [line(header), line(rule), ...rows.map(line)].join("\n");
}

export function renderResults(summaries: readonly RunSummary[]): string {
  const out: string[] = [
    "# Search eval results",
    "",
    "Generated by `npm run search-eval:report` from the runs in `results/`. Do not edit by hand.",
    "See [README.md](README.md) for what is measured and how to read it.",
    "",
    "## Runs",
    "",
    table(
      [
        "Run",
        "Mode",
        "Commit",
        "Passages",
        "Queries",
        "Hit@10",
        "nDCG@10",
        "Recall@100",
        "MRR@10",
        "In-memory ranker",
        "p95 query",
      ],
      summaries.map((s) => [
        `${s.name}${s.limits.maxPassages === null && s.limits.maxQueries === null ? "" : " (partial)"}`,
        s.mode,
        `${s.source.commit.slice(0, 9)}${s.source.dirty ? " (dirty)" : ""}`,
        s.totals.passages.toLocaleString("en-US"),
        s.totals.queries.toLocaleString("en-US"),
        fmt(s.macro.hit10),
        fmt(s.macro.ndcg10),
        fmt(s.macro.recall100),
        fmt(s.macro.mrr10),
        `${Math.round((100 * s.languages.reduce((n, l) => n + (l.lexicalEngines.memory ?? 0), 0)) / s.totals.queries)}%`,
        `${s.timing.queryMsP95} ms`,
      ]),
    ),
    "",
    'The four scores are macro averages: every language counts equally. "In-memory ranker" is the',
    "share of queries the default keyword ranker served; the FTS5 fallback served the rest.",
  ];
  const languages = [...new Set(summaries.flatMap((s) => s.languages.map((l) => l.language)))].sort(
    (a, b) => LANGUAGE_NAMES[a].localeCompare(LANGUAGE_NAMES[b]),
  );
  for (const metric of ["hit10", "ndcg10", "recall100"] as const) {
    out.push(
      "",
      `## ${METRIC_LABELS[metric]} by language`,
      "",
      table(
        ["Language", ...summaries.map((s) => s.name)],
        languages.map((language) => [
          LANGUAGE_NAMES[language],
          ...summaries.map((s) => {
            const result = s.languages.find((l) => l.language === language);
            return result ? fmt(result[metric]) : "—";
          }),
        ]),
      ),
    );
  }
  return `${out.join("\n")}\n`;
}

function byLanguage(rows: readonly QueryRow[]): Map<Language, Map<string, QueryRow>> {
  const grouped = new Map<Language, Map<string, QueryRow>>();
  for (const row of rows) {
    let queries = grouped.get(row.language);
    if (!queries) grouped.set(row.language, (queries = new Map()));
    queries.set(row.queryId, row);
  }
  return grouped;
}

/** Two runs compare only when they searched the same passages for the same questions. */
function assertSameDataset(a: RunSummary, b: RunSummary): void {
  const pools = (s: RunSummary): string =>
    JSON.stringify([
      s.dataset,
      s.limits,
      s.languages.map((l) => [l.language, l.pool, l.passages]).sort(),
    ]);
  if (pools(a) !== pools(b)) {
    throw new Error(
      `${a.name} and ${b.name} were not run on the same languages, pools and caps, ` +
        "so their scores cannot be compared",
    );
  }
}

export function renderComparison(
  base: { summary: RunSummary; rows: readonly QueryRow[] },
  candidate: { summary: RunSummary; rows: readonly QueryRow[] },
  metric: Metric,
): string {
  assertSameDataset(base.summary, candidate.summary);
  const baseRows = byLanguage(base.rows);
  const candidateRows = byLanguage(candidate.rows);
  const random = seededRandom(BOOTSTRAP_SEED);
  const languages = [...baseRows.keys()].sort((a, b) =>
    LANGUAGE_NAMES[a].localeCompare(LANGUAGE_NAMES[b]),
  );

  const pairs = new Map<Language, { a: number[]; b: number[] }>();
  for (const language of languages) {
    const a: number[] = [];
    const b: number[] = [];
    const theirs = candidateRows.get(language)!;
    for (const [queryId, row] of baseRows.get(language)!) {
      const other = theirs.get(queryId);
      if (!other) throw new Error(`${language} query ${queryId} is missing from the second run`);
      a.push(row[metric]);
      b.push(other[metric]);
    }
    if (a.length !== theirs.size) {
      throw new Error(`The two runs scored different ${language} queries`);
    }
    pairs.set(language, { a, b });
  }

  const rows = languages.map((language) => {
    const { a, b } = pairs.get(language)!;
    const result = pairedBootstrap(a, b, random, BOOTSTRAP_ROUNDS);
    const verdict = result.low > 0 ? "better" : result.high < 0 ? "worse" : "no clear change";
    return [
      LANGUAGE_NAMES[language],
      String(a.length),
      fmt(mean(a)),
      fmt(mean(b)),
      signed(result.difference),
      `${signed(result.low)} to ${signed(result.high)}`,
      verdict,
    ];
  });

  // The macro interval resamples queries within each language, then averages
  // the languages, so each keeps its equal weight.
  const macroDeltas: number[] = [];
  for (let round = 0; round < BOOTSTRAP_ROUNDS; round += 1) {
    let sum = 0;
    for (const { a, b } of pairs.values()) {
      let delta = 0;
      for (let i = 0; i < a.length; i += 1) {
        const pick = Math.floor(random() * a.length);
        delta += b[pick]! - a[pick]!;
      }
      sum += delta / a.length;
    }
    macroDeltas.push(sum / pairs.size);
  }
  const macroBase = mean([...pairs.values()].map((p) => mean(p.a)));
  const macroCandidate = mean([...pairs.values()].map((p) => mean(p.b)));
  const low = percentile(macroDeltas, 0.025);
  const high = percentile(macroDeltas, 0.975);
  rows.push([
    "**All languages**",
    String([...pairs.values()].reduce((n, p) => n + p.a.length, 0)),
    `**${fmt(macroBase)}**`,
    `**${fmt(macroCandidate)}**`,
    `**${signed(macroCandidate - macroBase)}**`,
    `${signed(low)} to ${signed(high)}`,
    low > 0 ? "better" : high < 0 ? "worse" : "no clear change",
  ]);

  return [
    `### ${METRIC_LABELS[metric]}: ${base.summary.name} → ${candidate.summary.name}`,
    "",
    table(
      [
        "Language",
        "Queries",
        base.summary.name,
        candidate.summary.name,
        "Change",
        "95% interval",
        "",
      ],
      rows,
    ),
    "",
  ].join("\n");
}

async function main(): Promise<void> {
  const argv = process.argv.slice(2);
  if (argv[0] === "--compare") {
    const [, baseName, candidateName] = argv;
    if (!baseName || !candidateName) {
      throw new Error("usage: search-eval:report -- --compare <base-run> <candidate-run>");
    }
    const base = { summary: readSummary(baseName), rows: readQueryRows(baseName) };
    const candidate = { summary: readSummary(candidateName), rows: readQueryRows(candidateName) };
    for (const metric of ["hit10", "ndcg10", "recall100"] as const) {
      process.stdout.write(`${renderComparison(base, candidate, metric)}\n`);
    }
    return;
  }
  const summaries = listRuns()
    .map((name) => readSummary(name))
    .sort((a, b) => (a.startedAt < b.startedAt ? -1 : 1));
  const path = join(RESULTS_DIR, "..", "RESULTS.md");
  // The page goes through the repository's formatter so the format check accepts it as generated.
  const config = await prettier.resolveConfig(path);
  writeFileSync(
    path,
    await prettier.format(renderResults(summaries), { ...config, filepath: path }),
  );
  process.stdout.write(`Wrote evals/search/RESULTS.md (${summaries.length} runs)\n`);
}

if (process.argv[1]?.endsWith("report.ts")) {
  main().catch((err: unknown) => {
    process.stderr.write(`${err instanceof Error ? err.message : String(err)}\n`);
    process.exit(1);
  });
}
