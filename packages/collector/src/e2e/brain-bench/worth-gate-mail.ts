export type WorthMailKey = keyof typeof WORTH_MAIL;

/** The mail as a bench document: an email with a sender in `metadata.people`. */
export function worthMailDoc(mail: WorthMail, extra: Partial<BenchDoc> = {}): BenchDoc {
  return {
    externalId: mail.externalId,
    title: mail.title,
    content: mail.content,
    documentType: "email",
    ...extra,
    metadata: { people: peopleOf(mail), ...(extra.metadata ?? {}) },
  };
}

/**
 * An attachment of `parent`: an `attachment` document declaring its container
 * through `metadata.extra.parentExternalId`, the way an email provider emits
 * one. The worth gate judges it by the parent email.
 */
export function attachmentOf(parent: WorthMail, externalId: string, title: string): BenchDoc {
  return {
    externalId,
    title,
    content: `Itinerary for ${parent.title}. Passenger: ${CAST.self.name}.`,
    documentType: "attachment",
    metadata: { extra: { parentExternalId: parent.externalId } },
  };
}

/** The exact request the worth gate sends for `mail` — built with the gateway's rubric. */
export function worthRequestFor(mail: WorthMail): DecisionRequest {
  return {
    state: emailWorthState({
      title: mail.title,
      content: mail.content,
      metadata: { people: peopleOf(mail) },
    }),
    questions: EMAIL_WORTH_QUESTIONS,
  };
}

/** The answers the scripted model gives `mail`. */
export function worthAnswersFor(mail: WorthMail): Record<string, DecisionAnswer> {
  const clamped = Math.max(0, Math.min(3, mail.score));
  // A two-level split around the score, so `probabilities` is a coherent
  // distribution whose expectation is the score.
  const floor = Math.min(2, Math.floor(clamped));
  const upper = clamped - floor;
  const probabilities: Record<string, number> = { "0": 0, "1": 0, "2": 0, "3": 0 };
  probabilities[String(floor)] = round(1 - upper);
  probabilities[String(floor + 1)] = round(upper);
  return {
    [EMAIL_WORTH_QUESTION_ID]: { type: "score", score: mail.score, confidence: 0.9, probabilities },
  };
}

function round(n: number): number {
  return Math.round(n * 1000) / 1000;
}

/** The mail whose subject is `subject`, or undefined. */
export function worthMailBySubject(subject: unknown): WorthMail | undefined {
  return Object.values(WORTH_MAIL).find((m) => m.title === subject);
}

/** Whether the gate lets `mail` through to an agent run. */
export function passesWorthGate(mail: WorthMail): boolean {
  return mail.score >= EMAIL_WORTH_THRESHOLD;
}

/**
 * The replay cassette for every mail in {@link WORTH_MAIL}, one line each, in
 * table order — the content of
 * `evals/universes/loops-test-life/decision-cassettes/worth-gate.jsonl`.
 */
export function worthGateCassetteLines(): string[] {
  return Object.values(WORTH_MAIL).map((mail) =>
    formatDecisionCassetteEntry(worthRequestFor(mail), {
      model: WORTH_GATE_MODEL_ID,
      answers: worthAnswersFor(mail),
      inputTokens: 480,
    }),
  );
}
