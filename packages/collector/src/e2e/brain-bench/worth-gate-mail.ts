/** The model id cassettes record, as the TypeSafe backend reports it. */
export const WORTH_GATE_MODEL_ID = "jev-1.13.0";

export { EMAIL_WORTH_QUESTION_ID, EMAIL_WORTH_THRESHOLD };

export interface WorthMail {
  /** Stable key a suite refers to the email by. */
  key: string;
  externalId: string;
  title: string;
  content: string;
  sender: { name: string; email: string };
  /** The worth score the scripted model answers with (levels 0–3). */
  score: number;
}

/** The sender/recipient metadata the rubric reads the `from` line out of. */
function peopleOf(mail: WorthMail): Record<string, unknown>[] {
  return [
    { role: "sender", name: mail.sender.name, emails: [mail.sender.email] },
    { role: "recipient", name: CAST.self.name, emails: [CAST.self.email] },
  ];
}

