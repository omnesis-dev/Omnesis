/**
 * The worth gate's invented mail — the emails the `brain-decision-*` suites
 * push, each with the score the scripted decision model gives it.
 *
 * One table serves three consumers, so they cannot drift apart:
 *  - the scripted decision server's policy (score by subject);
 *  - the expected request a suite asserts the gate sent (built with the
 *    gateway's own rubric, `emailWorthState` + `EMAIL_WORTH_QUESTIONS`);
 *  - the committed replay cassettes under
 *    `evals/universes/loops-test-life/decision-cassettes/`, regenerated by
 *    `npx tsx scripts/write-worth-gate-cassettes.mjs` and held in sync by
 *    `worth-gate-mail.test.ts`.
 *
 * Everything here is invented: fictional senders on RFC-2606 reserved
 * domains, fictional vendors and places.
 */

