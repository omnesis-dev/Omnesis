/**
 * Properties of the whole reference set, from one replay of each.
 *
 * The paired half of the evaluation scores a compilation by replaying it and
 * comparing what it did to what the reference did. That comparison is worth
 * exactly as much as the reference's behaviour is specific. A reference that
 * fires once is matched by any plan that fires at the same moment for any
 * reason, so a corpus where most references fire once yields a headline that
 * agrees with plans it has no evidence about.
 *
 * The properties below fail for different reasons.
 *
 * **Distinctness** is the floor beneath the floor. If two references behave
 * identically then one of them is scoring compilations against the other's
 * question, and no amount of firing count fixes that.
 *
 * **Entropy** is how hard a reference is to match by accident. Three firings or
 * five model reaches is the bar: below it a single coincidence is agreement,
 * above it a plan has to be right repeatedly. A watch that fires `once_ever`
 * cannot clear the firing half by construction, so it is exempted — from its
 * own declared policy, not from a list someone can add to.
 *
 * **Saying anything at all** is the last two: a reference that fires nothing and
 * reaches nothing is equivalent to every other empty one, and a reference
 * truncated by a crash describes the probe rather than the watch.
 *
 * What the floor cannot see: a watch whose only judgement is an agent reading a
 * window — `major-life-turning-point` — clears it on three firings that its
 * weekly tick and thirty-day cooldown produce whatever the journal contains.
 * The probe cannot simulate what such an investigation would find, and
 * scripting a verdict per week would move the evasion from the cron into the
 * script rather than removing it. What would remove it is a journal with
 * turning points spaced to survive the cooldown; until then this reference
 * clears the floor without the corpus distinguishing anything, and saying so
 * here is worth more than an exemption that never runs.
 *
 * Every corpus-wide property lives here rather than being spread across files,
 * because each one costs a full replay of every watch and they can share one.
 * The replays are real rather than read off the frozen traces: a golden is
 * regenerated by the same command that would paper over the change this is
 * meant to catch.
 */

import { describe, expect, it } from "vitest";

import { watchNames } from "../backtest/golden.js";
import { loadWatch } from "../runtime/run.js";
import { behaviourOf, compareBehaviour, type Behaviour } from "./score.js";
import { LATITUDES } from "./free-parameters.js";

/**
 * Replaying seventeen watches over a season, once, for the whole file.
 *
 * Started on first use rather than at import, so a failure reading the corpus
 * lands inside the test that asked for it with that test's name on it, instead
 * of as a file-level unhandled rejection with nothing to point at.
 */
let started: Promise<Map<string, Behaviour>> | null = null;

function allBehaviours(): Promise<Map<string, Behaviour>> {
  started ??= (async () => {
    const measured = new Map<string, Behaviour>();
    // Replayed under its own answer key, which is the replay the evaluation
    // grades. Without the reference a selective watch is judged by the agreeing
    // probe instead, and every guard here would measure a behaviour the scorer
    // never sees.
    for (const name of watchNames()) {
      measured.set(name, await behaviourOf(loadWatch(name), { reference: name }));
    }
    return measured;
  })();
  return started;
}

const WHOLE_CORPUS_MS = 300_000;

/**
 * What it takes for a reference to be more than a coincidence.
 *
 * Either bar on its own is enough. A procedural watch reaches no model at all
 * and has only its firings; a judged one fires nothing in a replay whose gates
 * all hold, and has only its reaches. Requiring both would fail every watch in
 * the corpus for being the kind of watch it is.
 */
const FIRINGS_FLOOR = 3;
const REACHES_FLOOR = 5;

function clearsTheFloor(behaviour: Behaviour): boolean {
  return behaviour.firings.length >= FIRINGS_FLOOR || behaviour.reaches.length >= REACHES_FLOOR;
}

describe("what the corpus can distinguish", () => {
  it(
    "gives no two references the same behaviour",
    async () => {
      const behaviours = await allBehaviours();
      const names = [...behaviours.keys()];
      const collisions: string[] = [];

      for (let i = 0; i < names.length; i += 1) {
        for (let j = i + 1; j < names.length; j += 1) {
          const mine = behaviours.get(names[i]!)!;
          const theirs = behaviours.get(names[j]!)!;
          if (compareBehaviour(mine, theirs).equivalent) {
            collisions.push(`${names[i]} and ${names[j]}`);
          }
        }
      }

      expect(
        collisions,
        "two references replay identically, so a compilation of either scores against both",
      ).toEqual([]);
    },
    WHOLE_CORPUS_MS,
  );

  it(
    "gives every reference more than one occasion to be right about",
    async () => {
      const behaviours = await allBehaviours();
      const thin: string[] = [];

      for (const [name, behaviour] of behaviours) {
        if (clearsTheFloor(behaviour)) continue;
        // A watch that fires once for all time is bounded by its own policy,
        // not by the corpus. Read off the definition rather than listed here,
        // so a `stays_active` watch cannot be quietly moved into the exemption.
        if (loadWatch(name).firing_policy === "once_ever") continue;
        thin.push(
          `${name} (${behaviour.firings.length} firings, ${behaviour.reaches.length} reaches)`,
        );
      }

      expect(
        thin,
        `a reference below ${FIRINGS_FLOOR} firings and ${REACHES_FLOOR} reaches is matched by ` +
          `one coincidence. Give the journal another occasion of whatever it watches for.`,
      ).toEqual([]);
    },
    WHOLE_CORPUS_MS,
  );

  it(
    "gives every reference something to say",
    async () => {
      // Empty on every axis is equivalent to every other empty behaviour, so a
      // request whose reference is empty cannot be scored at all — every
      // compilation of it, right or wrong, matches.
      const behaviours = await allBehaviours();
      const silent = [...behaviours]
        .filter(([, b]) => b.firings.length === 0 && b.totalReaches === 0)
        .map(([name]) => name);
      expect(silent).toEqual([]);
    },
    WHOLE_CORPUS_MS,
  );

  it(
    "has no reference that threw on its way there",
    async () => {
      // A crashed replay stops at the event that threw, so everything after it
      // is simply absent and the behaviour describes the probe rather than the
      // watch. A judge stub answering `{}` produces exactly this: the travel
      // watch's date arithmetic runs on a null and the replay ends at the
      // fourteenth event.
      const behaviours = await allBehaviours();
      const crashed = [...behaviours]
        .filter(([, b]) => b.crashedAt !== null)
        .map(([name, b]) => `${name} at ${b.crashedAt}`);
      expect(crashed).toEqual([]);
    },
    WHOLE_CORPUS_MS,
  );

  it(
    "gives every firing something of its own to report",
    async () => {
      // What a firing hands back is compared by asking whether the compilation
      // reported everything the reference did. A reference that reports nothing
      // comparable — a payload that is all constants, or all node names, both of
      // which are dropped — makes that question vacuous: every compilation
      // covers an empty set, including one that hands back the wrong document.
      const behaviours = await allBehaviours();
      const silent = [...behaviours]
        .filter(([, b]) => b.firings.some((f) => f.reported.length === 0))
        .map(([name]) => name);
      expect(
        silent,
        "a reference fires without reporting anything a compilation could be held to",
      ).toEqual([]);
    },
    WHOLE_CORPUS_MS,
  );

  it(
    "never names more reaches than it counted",
    async () => {
      // The list is read off the trace and the total off the judge, so they are
      // two measurements of one thing. The list is the smaller by construction
      // — it names only the event-driven evaluations — and an extraction that
      // double-counted a re-evaluation would break the ordering.
      const behaviours = await allBehaviours();
      const overcounted = [...behaviours]
        .filter(([, b]) => b.reaches.length > b.totalReaches)
        .map(([name, b]) => `${name}: ${b.reaches.length} named, ${b.totalReaches} counted`);
      expect(overcounted).toEqual([]);
    },
    WHOLE_CORPUS_MS,
  );

  it(
    "grades a key that the request asked to be kept apart",
    async () => {
      // The other half of the `key-vocabulary` declaration. A watch that
      // declares it says its request names no instance dimension, so its key is
      // read as the partition it induces rather than as the values it holds.
      // A watch that does *not* declare it is claiming the opposite — "for the
      // same job", "in the current calendar month", "a proposal to a client" —
      // and that claim is only worth anything if the journal actually gives it
      // more than one instance to hold apart.
      //
      // Without this, narrowing the journal until one of those references sees
      // a single job would quietly stop grading the very thing its request
      // names, and nothing would redden.
      // Checked in both directions, because skipping the watches that declare
      // the latitude would make declaring it an escape hatch: a watch whose
      // request plainly names a month could claim otherwise and no test would
      // notice. Declaring it is a claim that the key separates nothing, and
      // that claim is as checkable as its opposite.
      const behaviours = await allBehaviours();
      const wrong: string[] = [];

      for (const [name, behaviour] of behaviours) {
        const declaresLatitude = (LATITUDES[name] ?? []).some((l) => l.rule === "key-vocabulary");
        const distinct = new Set(behaviour.firings.map((f) => f.key)).size;
        if (declaresLatitude && distinct > 1) {
          wrong.push(
            `${name} declares its key separates nothing, but it holds ${distinct} apart — ` +
              `so the latitude is excusing a key that is doing real work`,
          );
        }
        if (!declaresLatitude && distinct < 2) {
          wrong.push(
            `${name}'s request names an instance dimension, but the journal gives it ${distinct} ` +
              `instance — the key is graded as separating nothing, which is not what was asked`,
          );
        }
      }

      expect(wrong).toEqual([]);
    },
    WHOLE_CORPUS_MS,
  );

  it(
    "rounds only where a number is actually reported, and not to nothing",
    async () => {
      // `numeric-precision` was declared by three watches and checked by none:
      // coarsening every tolerance to whole numbers left the suite green, and
      // so did granting one to a watch that reports no number at all. Whether a
      // watch reports a number is a property of its replay, not of its text, so
      // it is measured here where the replays already exist.
      const behaviours = await allBehaviours();
      const wrong: string[] = [];

      for (const [name, behaviour] of behaviours) {
        const declared = (LATITUDES[name] ?? []).find((l) => l.rule === "numeric-precision");
        const reportsANumber = behaviour.firings.some((f) =>
          f.reported.some((value) => value.numeric !== null),
        );
        if (declared && !reportsANumber) {
          wrong.push(`${name} declares a rounding tolerance but reports no number for it to round`);
        }
        if (!declared && reportsANumber) {
          wrong.push(
            `${name} reports a number and declares no tolerance, so its exact digits are graded`,
          );
        }
        if (declared && (declared.places ?? 0) < 1) {
          wrong.push(
            `${name} rounds to whole numbers, coarse enough to hide a difference its request names`,
          );
        }
      }

      expect(wrong).toEqual([]);
    },
    WHOLE_CORPUS_MS,
  );

  it(
    "does not clear the floor by exempting most of the corpus",
    async () => {
      // The check above is satisfiable by declaring everything `once_ever`.
      // This is the counterweight: most of the corpus has to clear the bar on
      // the evidence rather than on its policy.
      const behaviours = await allBehaviours();
      const clearing = [...behaviours.values()].filter(clearsTheFloor).length;
      expect(
        clearing * 2,
        `only ${clearing} of ${behaviours.size} references clear the floor`,
      ).toBeGreaterThan(behaviours.size);
    },
    WHOLE_CORPUS_MS,
  );
});
