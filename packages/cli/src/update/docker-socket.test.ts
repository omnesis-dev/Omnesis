import { mkdtempSync, rmSync } from "node:fs";
import { createServer, type Server } from "node:net";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { afterEach, describe, expect, test } from "vitest";
import {
  dockerReinstallCommand,
  explainDeniedSocket,
  nodeDockerSocketProbeDeps,
  probeDockerSocket,
  withUpdaterGroup,
  type DockerSocketProbeDeps,
} from "./docker-socket.js";

/** The updater block as the installer writes it, for an account in group 20. */
function compose({
  groupAdd = ['      - "20"'],
  gateway = true,
  collector = true,
  image = "omnesis-gateway",
  extra = [] as string[],
} = {}): string {
  return [
    "# Generated by the Omnesis installer (install.sh --docker). Re-running the",
    "name: omnesis",
    "services:",
    ...(gateway
      ? [
          "  gateway:",
          `    image: "ghcr.io/omnesis-dev/${image}:\${OMNESIS_IMAGE_TAG}"`,
          '    user: "501:20"',
          ...extra,
          "    volumes:",
          "      - /Users/maya/.config/omnesis:/Users/maya/.config/omnesis",
        ]
      : []),
    ...(collector
      ? [
          "  collector:",
          '    image: "ghcr.io/omnesis-dev/omnesis-collector:${OMNESIS_IMAGE_TAG}"',
          '    user: "501:20"',
          "    environment:",
          "      - OMNESIS_GATEWAY_URL=https://gateway.example.com:7600",
        ]
      : []),
    "  updater:",
    '    profiles: ["update"]',
    '    image: "ghcr.io/omnesis-dev/omnesis-updater:${OMNESIS_IMAGE_TAG}"',
    '    user: "501:20"',
    ...(groupAdd.length > 0 ? ["    group_add:", ...groupAdd] : []),
    "    volumes:",
    "      - /Users/maya/.docker/run/docker.sock:/var/run/docker.sock",
    "",
  ].join("\n");
}

describe("withUpdaterGroup", () => {
  test("replaces the updater's group, and nothing else", () => {
    const text = compose();
    const fixed = withUpdaterGroup(text, 0)!;
    expect(fixed).toBe(text.replace('    group_add:\n      - "20"', '    group_add:\n      - "0"'));
    // The daemons' own accounts are not the updater's to change.
    expect(fixed.match(/user: "501:20"/gu)).toHaveLength(3);
  });

  test("adds a group to an updater that had none, after its account", () => {
    const fixed = withUpdaterGroup(compose({ groupAdd: [] }), 0)!;
    expect(fixed).toContain('    user: "501:20"\n    group_add:\n      - "0"\n    volumes:');
  });

  test("collapses several groups into the one that opens the socket", () => {
    const fixed = withUpdaterGroup(compose({ groupAdd: ['      - "20"', '      - "12"'] }), 0)!;
    expect(fixed).toContain('    group_add:\n      - "0"\n    volumes:');
    expect(fixed).not.toContain('"12"');
  });

  test("is no change when the updater already joins that group", () => {
    expect(withUpdaterGroup(compose(), 20)).toBeNull();
  });

  test("leaves a project it does not recognise alone", () => {
    expect(withUpdaterGroup("services:\n  updater: {}\n", 0)).toBeNull();
    expect(withUpdaterGroup("services:\n  gateway:\n    user: x\n", 0)).toBeNull();
  });
});

describe("dockerReinstallCommand", () => {
  const line = (flags: string) => `curl -fsSL https://omnesis.dev/install.sh | sh -s -- ${flags}`;

  test.each([
    ["a gateway and its collector", compose(), "--docker"],
    [
      "one combined container",
      compose({ collector: false, image: "omnesis-combined" }),
      "--docker --combined",
    ],
    ["a gateway alone", compose({ collector: false }), "--docker --gateway-only"],
    [
      "a collector of another machine's gateway",
      compose({ gateway: false }),
      "--docker --collector --gateway-url https://gateway.example.com:7600",
    ],
    [
      "a gateway on another port",
      compose({ extra: ["    ports:", '      - "17600:7600"'] }),
      "--docker --port 17600",
    ],
    [
      "host networking on another port",
      compose({
        extra: ["    network_mode: host", "    environment:", "      - OMNESIS_GATEWAY_PORT=17600"],
      }),
      "--docker --docker-network host --port 17600",
    ],
  ])("%s", (_label, text, flags) => {
    expect(dockerReinstallCommand(text)).toBe(line(flags));
  });
});

describe("probeDockerSocket", () => {
  const deps = (code: string | null, over: Partial<DockerSocketProbeDeps> = {}) => ({
    env: {},
    connect: () => Promise.resolve(code),
    socketGid: () => 0,
    groups: () => [20, 501],
    inContainer: () => true,
    ...over,
  });

  test("a socket that answers is reachable", async () => {
    await expect(probeDockerSocket(deps(null))).resolves.toEqual({ kind: "ok" });
  });

  test("a refused socket reports the group it belongs to and the groups this has", async () => {
    await expect(probeDockerSocket(deps("EACCES"))).resolves.toEqual({
      kind: "denied",
      socketGid: 0,
      groups: [20, 501],
      inContainer: true,
    });
  });

  test("anything else is Docker's to report", async () => {
    await expect(probeDockerSocket(deps("ENOENT"))).resolves.toEqual({ kind: "unknown" });
    // A client pointed at another daemon never uses the mounted socket.
    const elsewhere = deps("EACCES", { env: { DOCKER_HOST: "tcp://192.0.2.10:2375" } });
    await expect(probeDockerSocket(elsewhere)).resolves.toEqual({ kind: "unknown" });
  });

  describe("against a real socket", () => {
    let dir: string;
    let server: Server | null = null;
    afterEach(() => {
      server?.close();
      server = null;
      rmSync(dir, { recursive: true, force: true });
    });

    test("connects and reports what refused it", async () => {
      dir = mkdtempSync(join(tmpdir(), "omnesis-socket-"));
      const path = join(dir, "docker.sock");
      server = createServer((socket) => socket.end());
      await new Promise<void>((resolve) => server!.listen(path, resolve));
      await expect(nodeDockerSocketProbeDeps.connect(path)).resolves.toBeNull();
      await expect(nodeDockerSocketProbeDeps.connect(join(dir, "absent.sock"))).resolves.toBe(
        "ENOENT",
      );
      expect(nodeDockerSocketProbeDeps.socketGid(path)).toBe(process.getgid?.());
    });
  });
});

describe("explainDeniedSocket", () => {
  const install = {
    composeFile: "/Users/maya/.config/omnesis/docker-compose.yml",
    previous: "0.7.2",
  };
  const denied = { kind: "denied" as const, socketGid: 0, groups: [20, 501], inContainer: true };

  test("in the updater, the compose file's updater is given the socket's group", () => {
    const written: string[] = [];
    const message = explainDeniedSocket(denied, { ...install, composeText: compose() }, (text) =>
      written.push(text),
    );
    expect(written).toEqual([withUpdaterGroup(compose(), 0)]);
    expect(message).toContain("permission denied");
    expect(message).toContain("Inside a container the socket belongs to group 0.");
    expect(message).toContain("Nothing was changed: this install still runs 0.7.2.");
    expect(message).toContain(`The updater in ${install.composeFile} now joins group 0.`);
    expect(message).toContain("Run `omnesis update` again.");
    expect(message).not.toContain("install.sh");
  });

  test.each([
    ["outside a container, whose view of the socket is not the updater's", { inContainer: false }],
    ["when the socket's group cannot be read", { socketGid: null }],
    ["when this process already has the socket's group", { socketGid: 20 }],
  ])("%s, it names the installer instead", (_label, over) => {
    const written: string[] = [];
    const message = explainDeniedSocket(
      { ...denied, ...over },
      { ...install, composeText: compose({ collector: false, image: "omnesis-combined" }) },
      (text) => written.push(text),
    );
    expect(written).toEqual([]);
    expect(message).toContain("Nothing was changed: this install still runs 0.7.2.");
    expect(message).toContain(
      "curl -fsSL https://omnesis.dev/install.sh | sh -s -- --docker --combined",
    );
  });

  test("a compose file it cannot write leaves the installer as the way", () => {
    const message = explainDeniedSocket(denied, { ...install, composeText: compose() }, () => {
      throw new Error("EROFS");
    });
    expect(message).toContain("Re-run the installer once");
    expect(message).not.toContain("now joins");
  });
});
