const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const GENERATED = "<!-- Generated by scripts/blog/build.mjs; edit website/blog/posts/*.md. -->";
const ORIGIN = "https://omnesis.dev";
