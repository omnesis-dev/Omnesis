const chrome = readFileSync(join(ROOT, "website/docs/index.html"), "utf8");
const nav = chrome
  .match(/<nav id="nav">[\s\S]*?<\/nav>/)[0]
  .replace('href="/docs/" aria-current="page"', 'href="/docs/"')
  .replace('href="/blog/"', 'href="/blog/" aria-current="page"')
