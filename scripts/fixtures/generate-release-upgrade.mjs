/** Ordinary tables: not SQLite's own, not virtual, not a virtual table's shadow. */
function plainTables(db) {
  const objects = db
    .prepare(
      "SELECT name, sql FROM sqlite_master WHERE type = 'table' AND name NOT LIKE 'sqlite_%'",
    )
    .all();
  const virtual = objects
    .filter((o) => /^CREATE VIRTUAL TABLE/i.test(o.sql ?? ""))
    .map((o) => o.name);
  return objects
    .map((o) => o.name)
    .filter((name) => !virtual.some((v) => name === v || name.startsWith(`${v}_`)))
    .sort();
}

function readRows(db, table) {
  const columns = db
    .prepare("SELECT name, type FROM pragma_table_info(?) ORDER BY cid")
    .all(table)
    .map((c) => (/BLOB/i.test(c.type) ? `hex("${c.name}") AS "${c.name}"` : `"${c.name}"`));
  const order = columns.map((_, index) => index + 1).join(", ");
  return db.prepare(`SELECT ${columns.join(", ")} FROM "${table}" ORDER BY ${order}`).all();
}
