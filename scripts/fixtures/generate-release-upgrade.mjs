// Run with tsx, pointing at a separate checkout of the published release.
// All data is invented here; this command never reads an installed database.
import { mkdtempSync, mkdirSync, readFileSync, writeFileSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { pathToFileURL, fileURLToPath } from "node:url";
import { execFileSync } from "node:child_process";
import { gzipSync } from "node:zlib";
import { createHash } from "node:crypto";

const checkout = process.argv[2];
if (!checkout)
  throw new Error("Usage: tsx scripts/fixtures/generate-release-upgrade.mjs <release-checkout>");
const root = resolve(checkout);
const revision = execFileSync("git", ["rev-parse", "HEAD"], { cwd: root, encoding: "utf8" }).trim();
const expectedRevision = "c77ba95ec";
if (!revision.startsWith(expectedRevision))
  throw new Error("Fixture must be generated by the pinned v0.4.22 release");
const load = (path) => import(pathToFileURL(join(root, path)).href);
const { createDatabase, setSyncState, upsertDocuments } = await load("packages/gateway/src/db.ts");
const { createDevice } = await load("packages/gateway/src/data/repositories/DeviceRepository.ts");
const { createSource } = await load("packages/gateway/src/data/repositories/SourceRepository.ts");
const { prepareDocumentsForWrite } = await load(
  "packages/gateway/src/data/repositories/DocumentRepository.ts",
);
const { createMergeRule } = await load("packages/gateway/src/domain/merge/rule-crud.ts");
const { allDescriptors } = await load("packages/collector/src/source-descriptors.ts");
const sourceTypes = [...new Set(allDescriptors.map((entry) => String(entry.id)))]
  .filter((id) => !id.endsWith("-synth"))
  .sort();
if (sourceTypes.length < 25 || !sourceTypes.includes("local-files"))
  throw new Error("Release source registry did not load completely");
const dir = mkdtempSync(join(tmpdir(), "omnesis-release-upgrade-"));
const path = join(dir, "release.db");
const db = createDatabase(path);
try {
  if (db.pragma("user_version", { simple: true }) !== 171) throw new Error("Expected schema 171");
  const device = createDevice(db, { name: "Fictional fixture collector", kind: "collector" });
  for (const type of sourceTypes) {
    const source = createSource(db, { type, accountId: "fixture", deviceId: device.id });
    // A preservation sentinel, not a claim that this is a valid provider cursor.
    setSyncState(db, source.id, { fixtureBookmark: type }, { icon: "fixture", label: type });
    upsertDocuments(
      db,
      prepareDocumentsForWrite([
        {
          providerId: "example",
          sourceId: source.id,
          externalId: "fixture-document",
          title: "Fictional upgrade document",
          content: "Synthetic migration preservation sample.",
          contentHash: "fixture-content",
          metadata: {},
          sourceCreatedAt: "2026-01-01T00:00:00.000Z",
          sourceUpdatedAt: "2026-01-01T00:00:00.000Z",
        },
      ]),
    );
  }
  db.exec(`
    INSERT INTO people (id, canonical_name, source, first_seen, last_seen, created_at, updated_at)
      VALUES ('fixture-person', 'Maya Reeves', 'contacts', '2026-01-01', '2026-01-01', '2026-01-01', '2026-01-01');
    INSERT INTO person_aliases (id, person_id, alias, alias_type, source_id, created_at)
      VALUES ('fixture-email', 'fixture-person', 'maya@example.org', 'email', 'apple-contacts:fixture', '2026-01-01'),
             ('fixture-lid', 'fixture-person', '7700900133', 'lid', 'whatsapp:fixture', '2026-01-01');
    INSERT INTO document_people (document_id, person_id, role)
      SELECT id, 'fixture-person', 'sender' FROM documents WHERE source_id = 'gmail:fixture';
    INSERT INTO person_equivalences (from_id, to_id, applied_at)
      VALUES ('fixture-former-person', 'fixture-person', '2026-01-01');
    INSERT INTO access_levels (id, name, revision, created_at, updated_at)
      VALUES ('fixture-access', 'Fictional read access', 2, 1767225600000, 1767225600000);
    INSERT INTO access_level_capabilities (level_id, capability, source_mode, source_ids)
      VALUES ('fixture-access', 'direct', 'allowlist', '["gmail:fixture"]');
  `);
  createMergeRule(db, {
    sideA: { aliasType: "email", alias: "maya@example.org" },
    sideB: { aliasType: "email", alias: "m.reeves@example.org" },
    winnerSide: "a",
    kind: "user",
    createdBy: "fixture-operator",
  });
  const before = {
    sources: db.prepare("SELECT id, type, account_id FROM sources ORDER BY id").all(),
    documents: db
      .prepare("SELECT id, source_id, external_id, content_hash FROM documents ORDER BY id")
      .all(),
    cursors: db
      .prepare("SELECT source_id, device_id, cursor FROM sync_state ORDER BY source_id, device_id")
      .all(),
    rules: db.prepare("SELECT * FROM merge_rules ORDER BY id").all(),
    accessLevels: db.prepare("SELECT * FROM access_levels ORDER BY id").all(),
    accessCapabilities: db
      .prepare("SELECT * FROM access_level_capabilities ORDER BY level_id, capability")
      .all(),
    equivalences: db.prepare("SELECT * FROM person_equivalences ORDER BY from_id").all(),
  };
  db.pragma("wal_checkpoint(TRUNCATE)");
  db.close();
  const output = fileURLToPath(
    new URL("../../packages/gateway/src/data/fixtures/release-171/", import.meta.url),
  );
  mkdirSync(output, { recursive: true });
  const compressed = gzipSync(readFileSync(path));
  writeFileSync(join(output, "gateway.db.gz"), compressed);
  writeFileSync(
    join(output, "manifest.json"),
    JSON.stringify(
      {
        release: "v0.4.22",
        revision,
        schema: 171,
        sha256: createHash("sha256").update(compressed).digest("hex"),
        before,
      },
      null,
      2,
    ) + "\n",
  );
} finally {
  if (db.open) db.close();
  rmSync(dir, { recursive: true, force: true });
}
