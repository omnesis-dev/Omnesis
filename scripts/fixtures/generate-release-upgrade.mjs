// Each pinned release, by the commit its tag names.
const releases = [
  { revision: "c77ba95ec", release: "v0.4.22", schema: 171, seed: seedV0422 },
  {
    revision: "7b56bd0ee1bad5ad52cfc17a530ae5c734ff1f4e",
    release: "v0.6.0",
    schema: 188,
    seed: seedV060,
  },
];
const pinned = releases.find((entry) => revision.startsWith(entry.revision));
if (!pinned)
  throw new Error(
    `Fixture must be generated by a pinned release: ${releases.map((r) => `${r.release} (${r.revision.slice(0, 9)})`).join(", ")}`,
  );
const output = process.argv[3]
  ? resolve(process.argv[3])
  : fileURLToPath(
      new URL(
        `../../packages/gateway/src/data/fixtures/release-${pinned.schema}/`,
        import.meta.url,
      ),
    );

const { createDatabase } = await load("packages/gateway/src/db.ts");
const dir = mkdtempSync(join(tmpdir(), "omnesis-release-upgrade-"));
const path = join(dir, "release.db");
const db = createDatabase(path);
try {
  if (db.pragma("user_version", { simple: true }) !== pinned.schema)
    throw new Error(`Expected schema ${pinned.schema}`);
  const { manifest, files } = await pinned.seed(db, dir);
  db.pragma("wal_checkpoint(TRUNCATE)");
  db.close();
  mkdirSync(output, { recursive: true });
  const compressed = gzipSync(readFileSync(path));
  writeFileSync(join(output, "gateway.db.gz"), compressed);
  writeFileSync(
    join(output, "manifest.json"),
    JSON.stringify(
      {
        release: pinned.release,
        revision,
        schema: pinned.schema,
        sha256: createHash("sha256").update(compressed).digest("hex"),
        ...manifest,
      },
      null,
      2,
    ) + "\n",
  );
  for (const [name, content] of Object.entries(files ?? {}))
    writeFileSync(join(output, name), content);
} finally {
  if (db.open) db.close();
  rmSync(dir, { recursive: true, force: true });
}

