// Run with: node --import tsx scripts/generate-source-scopes.mjs [--check]
import { access, readFile, readdir, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { format } from "prettier";

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const providers = join(root, "packages/providers");
const entries = [];
const seen = new Set();
for (const directory of (await readdir(providers, { withFileTypes: true })).sort((a, b) =>
  a.name < b.name ? -1 : a.name > b.name ? 1 : 0,
)) {
  if (!directory.isDirectory()) continue;
  const file = join(providers, directory.name, "src/scope-contracts.ts");
  try {
    await access(file);
  } catch (error) {
    if (error.code === "ENOENT") continue;
    throw error;
  }
  const { scopeContracts } = await import(pathToFileURL(file).href);
  if (!scopeContracts || typeof scopeContracts !== "object" || Array.isArray(scopeContracts))
    throw new Error(`Invalid scope contracts: ${directory.name}`);
  for (const [sourceType, scopes] of Object.entries(scopeContracts)) {
    if (seen.has(sourceType)) throw new Error(`Duplicate scope source type: ${sourceType}`);
    seen.add(sourceType);
    entries.push({ sourceType, scopes });
  }
}
entries.sort((a, b) => (a.sourceType < b.sourceType ? -1 : a.sourceType > b.sourceType ? 1 : 0));
const output = await format(
  `// SPDX-License-Identifier: AGPL-3.0-or-later
// Copyright (c) 2026 Adrien Conrath

// Generated by scripts/generate-source-scopes.mjs from pure provider contracts.
// Edit the provider's scope-contracts.ts, then regenerate this catalogue.
import type { SourceScopesEntry } from "./scope-descriptors.js";

export const PACKAGED_SOURCE_SCOPES = ${JSON.stringify(entries, null, 2)} satisfies SourceScopesEntry[];
`,
  { parser: "typescript" },
);
const target = join(root, "packages/gateway/src/access/source-scope-catalog.generated.ts");
if (process.argv.includes("--check")) {
  if ((await readFile(target, "utf8")) !== output)
    throw new Error(
      "Packaged source scope catalogue is stale. Run node --import tsx scripts/generate-source-scopes.mjs.",
    );
} else await writeFile(target, output);
